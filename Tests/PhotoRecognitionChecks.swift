import Foundation
import UIKit
import ImageIO

@main struct VisionChecks {
    static func main() async throws {
        precondition(PhotoRecognitionService.kind(for: ["school_bus"]) == .other)
        precondition(PhotoRecognitionService.kind(for: ["sunflower"]) == .flower)
        precondition(PhotoRecognitionService.kind(for: ["hummingbird"]) == .bird)
        precondition(PhotoRecognitionService.kind(for: ["palm_tree"]) == .tree)
        precondition(PhotoRecognitionService.metadata(from: Data("bad image".utf8)) == nil)
        let format = UIGraphicsImageRendererFormat()
        format.scale = 1
        let image = UIGraphicsImageRenderer(size: CGSize(width: 40, height: 40), format: format).image { _ in
            UIColor.green.setFill()
            UIRectFill(CGRect(x: 0, y: 0, width: 40, height: 40))
        }
        func encodedImage(properties: [String: Any], type: String = "public.jpeg") -> Data? {
            let data = NSMutableData()
            guard let destination = CGImageDestinationCreateWithData(data, type as CFString, 1, nil) else { return nil }
            CGImageDestinationAddImage(destination, image.cgImage!, properties as CFDictionary)
            guard CGImageDestinationFinalize(destination) else { return nil }
            return data as Data
        }
        let properties: [String: Any] = [
            kCGImagePropertyGPSDictionary as String: [
                kCGImagePropertyGPSLatitude as String: 37.3195,
                kCGImagePropertyGPSLatitudeRef as String: "N",
                kCGImagePropertyGPSLongitude as String: 122.045,
                kCGImagePropertyGPSLongitudeRef as String: "W"
            ],
            kCGImagePropertyExifDictionary as String: [
                kCGImagePropertyExifDateTimeOriginal as String: "2026:10:16 12:00:00",
                kCGImagePropertyExifOffsetTimeOriginal as String: "-07:00"
            ]
        ]
        let data = encodedImage(properties: properties)!
        let metadata = PhotoRecognitionService.metadata(from: data)!
        precondition(abs(metadata.latitude! - 37.3195) < 0.0001)
        precondition(abs(metadata.longitude! + 122.045) < 0.0001)
        precondition(metadata.coordinate != nil)
        let expected = ISO8601DateFormatter().date(from: "2026-10-16T19:00:00Z")!
        precondition(abs(metadata.takenAt!.timeIntervalSince(expected)) < 1)

        let noGPS = encodedImage(properties: [:])!
        precondition(PhotoRecognitionService.metadata(from: noGPS)?.coordinate == nil)
        if CommandLine.arguments.count > 4, !CommandLine.arguments[4].isEmpty {
            let fixtureDirectory = URL(fileURLWithPath: CommandLine.arguments[4], isDirectory: true)
            try FileManager.default.createDirectory(at: fixtureDirectory, withIntermediateDirectories: true)
            var fixtureProperties = properties
            fixtureProperties[kCGImagePropertyGPSDictionary as String] = [
                kCGImagePropertyGPSLatitude as String: 37.32121,
                kCGImagePropertyGPSLatitudeRef as String: "N",
                kCGImagePropertyGPSLongitude as String: 122.04321,
                kCGImagePropertyGPSLongitudeRef as String: "W"
            ]
            let fixtureData = encodedImage(properties: fixtureProperties)!
            let fixtureMetadata = PhotoRecognitionService.metadata(from: fixtureData)!
            precondition(abs(fixtureMetadata.latitude! - 37.32121) < 0.00001)
            precondition(abs(fixtureMetadata.longitude! + 122.04321) < 0.00001)
            try fixtureData.write(to: fixtureDirectory.appendingPathComponent("gps-fixture.jpg"), options: .atomic)
            try noGPS.write(to: fixtureDirectory.appendingPathComponent("unlocated-fixture.jpg"), options: .atomic)
            let provenance = """
            # Synthetic photo metadata fixtures

            These 40 × 40 solid-green images are generated by Tests/PhotoRecognitionChecks.swift with UIGraphicsImageRenderer and ImageIO. They are synthetic software test fixtures, not photographs, real campus sightings, or evidence that a subject was observed at any location. No official or downloaded photo was modified to create them.

            - gps-fixture.jpg: synthetic GPS test point 37.32121, -122.04321, deliberately different from the app's initial map center; synthetic EXIF capture time 2026-10-16 12:00:00 -07:00. These coordinates are a test input, not a measured observation location.
            - unlocated-fixture.jpg: the same synthetic pixels with no GPS or capture-date metadata.

            Use these files to test ordinary PhotosPicker import, GPS extraction, map placement, and the manual-location requirement for an unlocated photo. Do not use them as real discoveries.

            Regenerate from the NatureRelay project directory:
            zsh Tests/run-photo-checks.sh Resources/test-flower.jpg flower Resources/PhotoMetadataFixtures

            """
            try provenance.write(to: fixtureDirectory.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
            print("EXPORTED: synthetic GPS and unlocated fixtures with provenance to \(fixtureDirectory.path)")
        }
        let dateOnly = encodedImage(properties: [
            kCGImagePropertyExifDictionary as String: properties[kCGImagePropertyExifDictionary as String]!
        ])!
        let dateOnlyMetadata = PhotoRecognitionService.metadata(from: dateOnly)!
        precondition(dateOnlyMetadata.coordinate == nil)
        precondition(abs(dateOnlyMetadata.takenAt!.timeIntervalSince(expected)) < 1)

        var southernProperties = properties
        southernProperties[kCGImagePropertyGPSDictionary as String] = [
            kCGImagePropertyGPSLatitude as String: 33.8688,
            kCGImagePropertyGPSLatitudeRef as String: "S",
            kCGImagePropertyGPSLongitude as String: 70.6693,
            kCGImagePropertyGPSLongitudeRef as String: "W"
        ]
        let southernMetadata = PhotoRecognitionService.metadata(from: encodedImage(properties: southernProperties)!)!
        precondition(abs(southernMetadata.latitude! + 33.8688) < 0.0001)
        precondition(abs(southernMetadata.longitude! + 70.6693) < 0.0001)

        precondition(PhotoMetadata(latitude: 37, longitude: nil, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: nil, longitude: -122, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: 91, longitude: 0, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: 0, longitude: -181, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: .nan, longitude: 0, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: 0, longitude: .infinity, takenAt: nil).coordinate == nil)
        precondition(PhotoMetadata(latitude: 0, longitude: 0, takenAt: nil).coordinate != nil)

        // ImageIO can normalize malformed GPS when encoding. Check parser rejection only when preserved.
        var malformedProperties = properties
        malformedProperties[kCGImagePropertyGPSDictionary as String] = [
            kCGImagePropertyGPSLatitude as String: 37.3195,
            kCGImagePropertyGPSLatitudeRef as String: "N"
        ]
        let partialData = encodedImage(properties: malformedProperties)!
        let partialSource = CGImageSourceCreateWithData(partialData as CFData, nil)!
        let partialProperties = CGImageSourceCopyPropertiesAtIndex(partialSource, 0, nil) as! [String: Any]
        let partialGPS = partialProperties[kCGImagePropertyGPSDictionary as String] as? [String: Any]
        if partialGPS?[kCGImagePropertyGPSLatitude as String] != nil && partialGPS?[kCGImagePropertyGPSLongitude as String] == nil {
            precondition(PhotoRecognitionService.metadata(from: partialData)?.coordinate == nil)
        }
        malformedProperties[kCGImagePropertyGPSDictionary as String] = [
            kCGImagePropertyGPSLatitude as String: 91.0,
            kCGImagePropertyGPSLatitudeRef as String: "N",
            kCGImagePropertyGPSLongitude as String: 122.0,
            kCGImagePropertyGPSLongitudeRef as String: "W"
        ]
        let invalidData = encodedImage(properties: malformedProperties)!
        let invalidSource = CGImageSourceCreateWithData(invalidData as CFData, nil)!
        let invalidProperties = CGImageSourceCopyPropertiesAtIndex(invalidSource, 0, nil) as! [String: Any]
        let invalidGPS = invalidProperties[kCGImagePropertyGPSDictionary as String] as? [String: Any]
        if let latitude = (invalidGPS?[kCGImagePropertyGPSLatitude as String] as? NSNumber)?.doubleValue, latitude > 90 {
            precondition(PhotoRecognitionService.metadata(from: invalidData)?.coordinate == nil)
        }

        if let heicData = encodedImage(properties: southernProperties, type: "public.heic") {
            let heicMetadata = PhotoRecognitionService.metadata(from: heicData)!
            precondition(abs(heicMetadata.latitude! + 33.8688) < 0.0001)
            precondition(abs(heicMetadata.longitude! + 70.6693) < 0.0001)
            precondition(abs(heicMetadata.takenAt!.timeIntervalSince(expected)) < 1)
            print("PASS: HEIC preserves signed photo GPS and timezone-aware capture date.")
        } else {
            print("SKIP: this simulator cannot encode HEIC metadata fixtures.")
        }
        let badge = PhotoRecognitionService.photoBadge(from: image)
        precondition(badge.size == CGSize(width: 600, height: 600))
        precondition(badge.pngData() != nil)
        print("PASS: broad labels, unrelated-photo category, corrupt image, absent/partial/invalid GPS, S/W EXIF GPS, timezone date, fallback badge.")

        func solid(_ color: UIColor) -> UIImage {
            UIGraphicsImageRenderer(size: CGSize(width: 40, height: 40), format: format).image { _ in
                color.setFill()
                UIRectFill(CGRect(x: 0, y: 0, width: 40, height: 40))
            }
        }
        precondition(PhotoRecognitionService.paletteHex(from: solid(.red), kind: .flower) == "#FF0000")
        precondition(PhotoRecognitionService.paletteHex(from: solid(.green), kind: .plant) == "#00FF00")
        precondition(PhotoRecognitionService.paletteHex(from: solid(.blue), kind: .bird) == "#0000FF")
        precondition(PhotoRecognitionService.paletteHex(from: solid(.white), kind: .flower) == nil)
        precondition(PhotoRecognitionService.paletteHex(from: solid(.black), kind: .bird) == nil)
        precondition(PhotoRecognitionService.paletteHex(from: solid(.clear), kind: .plant) == nil)
        print("PASS: measured RGB palettes match red/green/blue photos; white, black and transparent have no invented palette.")

        if CommandLine.arguments.count > 1 {
            let path = CommandLine.arguments[1]
            guard let photo = UIImage(contentsOfFile: path) else { fatalError("Could not load test photo at \(path)") }
            let modelURL = CommandLine.arguments.count > 2 ? URL(fileURLWithPath: CommandLine.arguments[2]) : nil
            let result = try await PhotoRecognitionService(modelURL: modelURL).recognize(image: photo)
            precondition(!result.label.isEmpty)
            precondition(result.confidence.isFinite && (0...1).contains(result.confidence))
            precondition(!result.alternatives.isEmpty && result.alternatives.count <= 5)
            precondition(result.sticker?.size == CGSize(width: 600, height: 600))
            precondition(result.sticker?.pngData() != nil)
            if CommandLine.arguments.count > 3 && !CommandLine.arguments[3].isEmpty {
                precondition(result.kind.rawValue == CommandLine.arguments[3], "The broad category did not match the fixture ground truth.")
            }
            print("ACTUAL VISION: label=\(result.label), kind=\(result.kind.rawValue), confidence=\(result.confidence), foregroundMask=\(result.usedForegroundMask), palette=\(result.paletteHex ?? "none")")
            print("PASS: actual sample produced labels and a valid sticker. This checks execution, not identification accuracy; review the labels against the photo.")
        }
    }
}
